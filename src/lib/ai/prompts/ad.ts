import type { ChannelProfile } from "@/lib/channel";
import type { ProductBrief } from "@/lib/types";
import { languageRule } from "./index";

const list = (xs: string[]) => xs.map((x) => `- ${x}`).join("\n");

/** System prompt for product-ad channels (the long-form channelBrief talks about YouTube explainers). */
export function adBrief(p: ChannelProfile): string {
  return `You are a senior performance-marketing copywriter and art director making 15–20 second vertical video ads (TikTok, Reels, Shorts).

<brand>
About: ${p.niche}
Voice: ${p.voice}
Rule: ${p.evidenceRule}
Other rules:
${list(p.extraScriptRules)}
Visual style: ${p.visual.styleAnchor.replace(/,\s*$/, "")}
</brand>

${languageRule(p)}`;
}

export function productBlock(b: ProductBrief) {
  return `<product>
Name: ${b.name}
Selling points:
${list(b.sellingPoints)}
${b.audience ? `Audience: ${b.audience}\n` : ""}${b.price ? `Price: ${b.price}\n` : ""}Call to action: ${b.cta}
</product>`;
}

export function adScriptPrompt(
  b: ProductBrief,
  opts: { feedback?: string; previous?: string; previousHooks?: string[]; silent?: boolean } = {},
) {
  const hooks = opts.previousHooks?.length
    ? `\n<previous_hooks>\n${list(opts.previousHooks)}\n</previous_hooks>\nEarlier ads for this product opened with the lines above. Use a clearly different hook and angle (another selling point first, another emotion), never a rewording of these.\n`
    : "";
  const silent = opts.silent
    ? "\nThis ad is SILENT: the lines are shown as big on-screen text, not spoken. Keep each sentence very short (3–9 words), punchy and easy to read in 3 seconds.\n"
    : "";
  return `${productBlock(b)}
${hooks}${silent}
Write the ${opts.silent ? "on-screen text" : "voiceover"} for a 15–20 second ad for this product.
- ${opts.silent ? "4–6 very short lines, 18–35 words in total (about 3 seconds of reading each)" : "3–5 short sentences, 40–55 words in total (about 17 seconds spoken)"}. Count the words.
- Sentence 1 is the hook: stop the scroll with a problem, a surprising benefit or a question.
- The middle sentences each sell ONE selling point as a concrete benefit the viewer feels.
- The last sentence is the call to action, built on "${b.cta}"${b.price ? ` (you may mention ${b.price})` : ""}.
- ${opts.silent ? "Plain readable text" : "Natural spoken language"}, no emojis, hashtags, stage directions or brackets.
${opts.previous ? `\n<previous_version>\n${opts.previous}\n</previous_version>\n` : ""}${opts.feedback ? `\nChange it like this: ${opts.feedback}\n` : ""}
Return the sentences in order.`;
}

export function adScenesPrompt(
  p: ChannelProfile,
  b: ProductBrief,
  numbered: string,
  sentenceCount: number,
  variety: { direction?: string | null; avoid?: string[] } = {},
) {
  const direction = variety.direction
    ? `\n<visual_direction>\n${variety.direction}\n</visual_direction>\nBuild every shot of this ad around this visual direction (settings, props, light, mood), varied from shot to shot within it.\n`
    : "";
  const avoid = variety.avoid?.length
    ? `\n<avoid>\n${list(variety.avoid)}\n</avoid>\nThese shots were already used in earlier ads for this product. Every new shot must clearly differ from them in setting, camera angle and props.\n`
    : "";
  const bgs = p.visual.backgrounds.map((x) => `- ${x.key}: ${x.description} (use for: ${x.mood})`).join("\n");
  const frames = p.visual.frameTypes.filter((f) => !f.textOnly).map((f) => `- ${f.key}: ${f.description}`).join("\n");
  return `${productBlock(b)}

${direction}${avoid}
Plan the shots for this ad's script (${sentenceCount} numbered sentences, 0-based):

<sentences>
${numbered}
</sentences>

Make one scene per sentence (fromSentence = toSentence), in order, covering every sentence. Each scene is ONE still image, generated by editing the product photo the creator uploaded, shown while its sentence is spoken.
- Scene 1 grabs attention (usually product_hero). Vary angles and settings so no two scenes look alike. Show the benefit each sentence talks about.
- The last scene shows the product clearly so it leads into the end card.

frameType must be one of:
${frames}

background must be one of these keys:
${bgs}

onScreenText: 1–4 punchy words in the ad's language that reinforce the sentence (e.g. "ALL-DAY BATTERY"), or "". It is overlaid by code, so NEVER put words in the description.

description (always in English, for the image model): start with "The exact product from the reference photo" and say where it is, its angle, what surrounds it, who (if anyone) is with it and what they do, the lighting and composition. Keep the product large and in the upper two thirds of a tall 9:16 frame. Never change the product's shape, colors, label or logo, never add text, and do not include style words (they are added automatically).`;
}
